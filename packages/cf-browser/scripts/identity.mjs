/**
 * Generates `packages/plugin-system/src/account/cf-identity.generated.ts` (openspec
 * cf-account-admin design.md A1): cf's OAuth client id and default scopes, read from the
 * `@cloudflare/workers-auth` version that the pinned cf commit declares. Nothing is copied by hand.
 *
 *   node packages/cf-browser/scripts/identity.mjs          write the file
 *   node packages/cf-browser/scripts/identity.mjs --check  fail when it is missing or stale
 *
 * Fails when the installed workers-auth is not the version cf's package.json pins.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(pkgRoot, '..', '..');
export const IDENTITY_FILE = join(repoRoot, 'packages', 'plugin-system', 'src', 'account', 'cf-identity.generated.ts');

async function readJson(path) {
  return JSON.parse(await readFile(path, 'utf8'));
}

/** The generated module's text. Needs the `.ref/cf` checkout (scripts/fetch-upstream.mjs). */
export async function identitySource() {
  const pin = await readJson(join(pkgRoot, 'upstream.json'));
  const cli = await readJson(join(repoRoot, '.ref', 'cf', 'packages', 'cli', 'package.json'));
  // cf bundles its dependencies, so the pin sits in devDependencies.
  const pinned = cli.dependencies?.['@cloudflare/workers-auth'] ?? cli.devDependencies?.['@cloudflare/workers-auth'];
  // ESM-only exports: resolve the way an import from this package would.
  const entry = fileURLToPath(import.meta.resolve('@cloudflare/workers-auth/cf'));
  // The package's exports do not list package.json; find it next to the resolved entry.
  let dir = dirname(entry);
  while (!(await readFile(join(dir, 'package.json'), 'utf8').then((text) => JSON.parse(text).name === '@cloudflare/workers-auth', () => false))) {
    const up = dirname(dir);
    if (up === dir) throw new Error('cannot find the package.json of @cloudflare/workers-auth');
    dir = up;
  }
  const installed = (await readJson(join(dir, 'package.json'))).version;
  if (pinned !== installed) {
    throw new Error(
      `cf ${pin.commit.slice(0, 7)} pins @cloudflare/workers-auth ${pinned}, but ${installed} is installed in packages/cf-browser`,
    );
  }

  // getClientIdFromEnv() honours CLOUDFLARE_CLIENT_ID; the generated file must hold cf's own id.
  const saved = process.env.CLOUDFLARE_CLIENT_ID;
  delete process.env.CLOUDFLARE_CLIENT_ID;
  let clientId;
  let scopes;
  try {
    const auth = await import(pathToFileURL(entry).href);
    clientId = auth.getClientIdFromEnv();
    scopes = [...auth.CF_CLI.getDefaultScopeKeys()];
  } finally {
    if (saved !== undefined) process.env.CLOUDFLARE_CLIENT_ID = saved;
  }
  if (typeof clientId !== 'string' || clientId === '' || !Array.isArray(scopes) || scopes.length === 0) {
    throw new Error('@cloudflare/workers-auth/cf no longer exposes the client id and default scopes this script reads');
  }

  return `/**
 * cf's OAuth identity (openspec cf-account-admin design.md A1). GENERATED by
 * packages/cf-browser/scripts/identity.mjs from @cloudflare/workers-auth ${installed}, the version
 * cloudflare/cf ${pin.commit} pins. Do not edit; rerun the script after changing the pin.
 */
export const CF_WORKERS_AUTH_VERSION = ${JSON.stringify(installed)};
export const CF_UPSTREAM_COMMIT = ${JSON.stringify(pin.commit)};
export const CF_CLIENT_ID = ${JSON.stringify(clientId)};
/** cf's default scopes; \`offline_access\` is appended when asking, as cf does. */
export const CF_DEFAULT_SCOPES: readonly string[] = ${JSON.stringify(scopes, null, 2).replace(/\n/g, '\n')};
`;
}

/** Writes the file, or with `check` only compares it. Returns whether the file was current. */
export async function writeIdentity({ check = false } = {}) {
  const want = await identitySource();
  const have = await readFile(IDENTITY_FILE, 'utf8').catch(() => null);
  if (have === want) return true;
  if (check) {
    throw new Error(`${IDENTITY_FILE} is ${have === null ? 'missing' : 'stale'}; run node packages/cf-browser/scripts/identity.mjs`);
  }
  await writeFile(IDENTITY_FILE, want);
  return false;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  writeIdentity({ check })
    .then((current) => console.log(current ? 'cf identity: up to date' : `cf identity: wrote ${IDENTITY_FILE}`))
    .catch((error) => {
      console.error(error instanceof Error ? error.message : error);
      process.exit(1);
    });
}
