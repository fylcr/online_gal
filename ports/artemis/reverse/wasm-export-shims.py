#!/usr/bin/env python3
"""
Re-expose a `wasm2c` module's exports under the names and signatures the original
WebAssembly module exported.

`wasm2c` turns each exported wasm function into a C function that takes an extra
leading `w2c_artemis*` instance pointer, and it renames anything that is not a
valid C identifier (`_c` -> `0x5Fc`).  Both changes are invisible from C, but they
mean the rebuilt module's export surface cannot be compared with the original's
directly -- the arities differ by one and some names differ.

This script reads the generated header's `/* export: 'X' */` blocks, strips the
instance pointer, and emits one wrapper per export under the ORIGINAL name.  The
wrappers share a single module instance, which is what the original module is:
one instance per instantiation.

Also emits `wasm_export_shims_init()`, which has to be called before any other
export -- `wasm2c_artemis_instantiate` is what runs the module's start-up.

Usage: wasm-export-shims.py <artemis.h> <out.c>
"""

import argparse
import os
import re
import sys

# One `/* export: 'NAME' */` comment followed by its declaration.  The return type
# is a core type alias, `void`, or the funcref-table pointer that the exported table
# comes back as.
BLOCK = re.compile(
    r"/\* export: '(?P<orig>[^']*)' \*/\s*"
    r"(?P<ret>void|f32|f64|u32|s32|u64|s64|u8|s8|u16|s16|wasm_rt_funcref_table_t\s*\*)\s+"
    r"(?P<name>w2c_artemis_[A-Za-z0-9_]+)\s*\((?P<args>[^)]*)\)\s*;",
    re.MULTILINE,
)

# The C identifier wasm2c chose for a non-identifier name: `_c` -> `0x5Fc`.
ESCAPE = re.compile(r"0x([0-9A-Fa-f]{2})")


def needs_escape(name: str) -> bool:
    """Whether `name` cannot be written directly as a C identifier."""
    return not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("header")
    ap.add_argument("out")
    args = ap.parse_args()

    text = open(args.header, encoding="utf-8", errors="replace").read()

    blocks = []
    skipped = []
    for m in BLOCK.finditer(text):
        orig = ESCAPE.sub(lambda h: chr(int(h.group(1), 16)), m.group("orig"))
        ret, name, arglist = m.group("ret"), m.group("name"), m.group("args").strip()
        # An exported TABLE does not become a function.  wasm2c hands back a pointer
        # to a C-side table struct, and the rebuilt module keeps that table in linear
        # memory rather than declaring a wasm table, so there is nothing to re-export.
        # The table is reported and skipped rather than silently dropped.
        if "funcref_table_t" in ret:
            skipped.append((orig, ret))
            continue
        # Drop the leading instance pointer; the wrapper supplies it.  The parameter
        # is unnamed in the header (the signature is all types), so the wrapper names
        # them p0, p1, ... in order.
        params = [p.strip() for p in arglist.split(",")]
        assert params and params[0].startswith("w2c_artemis"), (orig, arglist)
        rest = params[1:]
        named = [(f"p{i}", t) for i, t in enumerate(rest)]
        blocks.append((orig, ret, name, named))

    ident = "".join(c for c in os.path.splitext(os.path.basename(args.out))[0] if c.isalnum()) or "mod"

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "/* Generated by wasm-export-shims.py -- do not edit.\n"
            " *\n"
            " * Re-exposes the wasm2c exports under the original module's names and\n"
            " * signatures, so the rebuilt module's export surface can be compared with\n"
            " * the one it was transpiled from.  See the script for why the instance\n"
            " * pointer has to be stripped.\n"
            " */\n"
            f'#include "{os.path.basename(args.header)}"\n'
            "#include \"wasm-rt.h\"\n"
            "\n"
            "static w2c_artemis g_instance;\n"
            "static int g_ready;\n"
            "\n"
            "/* Instantiate once, before anything can call an export.  Every export below\n"
            " * reads this instance, which is what the original module is: one instance per\n"
            " * instantiation. */\n"
            "static void wasm_export_shims_init(void) {\n"
            "  if (g_ready) return;\n"
            "  wasm_rt_init();\n"
            "  wasm2c_artemis_instantiate(&g_instance, 0);\n"
            "  g_ready = 1;\n"
            "}\n"
            "\n"
            "/* The constructor attribute alone is NOT enough, and the reason is worth stating:\n"
            " * the official glue treats the export named `Mc` as `___wasm_call_ctors`\n"
            " * (`Module[\"___wasm_call_ctors\"] = Module[\"asm\"][\"Mc\"]`), and the transpiled\n"
            " * module has its own guest function of that name. So when the glue runs the\n"
            " * module's start-up it calls *this* wrapper, not the init above -- an ordering\n"
            " * that is not ours to choose. Every wrapper therefore checks first, and the\n"
            " * constructor remains only as a fallback for embedders that call something else\n"
            " * first. Without this the instance pointer stayed null and the very first access\n"
            " * trapped reading `(*NULL).size`, which is exactly what the browser showed. */\n"
            "__attribute__((constructor))\n"
            "static void wasm_export_shims_ctor(void) { wasm_export_shims_init(); }\n"
            "\n"
            f"/* {len(blocks)} exports. */\n"
        )
        for orig, ret, name, named in blocks:
            # The wrapper's C name has to be a legal identifier even when the export
            # name is not, so it is derived deterministically: identifier characters
            # are kept, everything else becomes `_HH`.  The ORIGINAL name rides along
            # in `export_name`, so the rebuilt module's export surface reads exactly
            # like the original's and wasm-diff.mjs needs no name-mapping table.
            suffix = re.sub(r"[^A-Za-z0-9]", lambda m: "_%02x" % ord(m.group(0)), orig)
            cname = f"artc_export_{suffix}"
            inner = ", ".join(["&g_instance"] + [n for n, _ in named])
            signature = ", ".join(f"{t} {n}" for n, t in named) if named else "void"
            f.write(f"/* export: '{orig}' */\n")
            f.write(f'__attribute__((export_name("{orig}")))\n')
            f.write(f"{ret} {cname}({signature}) {{\n")
            f.write("  wasm_export_shims_init();\n")
            call = f"{name}({inner})"
            f.write(f"  return {call};\n" if ret != "void" else f"  {call};\n")
            f.write("}\n")

    print(f"{os.path.basename(args.out)}: {len(blocks)} export shims")
    for orig, ret in skipped:
        print(f"  skipped (table, not a function): '{orig}' -> {ret.strip()}")
    for orig, ret, name, named in blocks:
        if needs_escape(orig):
            print(f"  non-identifier export name: '{orig}'")


if __name__ == "__main__":
    sys.exit(main())
