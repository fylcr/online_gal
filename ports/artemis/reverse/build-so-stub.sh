#!/usr/bin/env bash
# Emit a C translation unit that defines exactly the dynamic symbols the official
# libartemis.so exports.
#
# Why a symbol stub and not the decompiled pseudo-C: Ghidra's output is written to
# be *read*, and it is not a compilable program. It refers to types that only exist
# in the original headers (`artemis::CArtemis`, `basic_string<...>` used as a cast
# target), it names hardware intrinsics as functions (`ExclusiveMonitorPass`), and
# its string literals are reconstructed as byte stacks rather than literals. No
# compiler accepts ~9,000 such functions. What can be rebuilt and checked is the
# ABI surface -- the names a caller resolves -- so that is what this emits, and
# rebuild.sh diffs it against the shipped binary.
#
# Symbol classes, and what each becomes:
#   T  strong function   ->  a real (empty) function
#   W  weak function     ->  a real function marked __attribute__((weak))
#   V  weak object       ->  a weak object   (these are the C++ template guard
#                            variables the babel headers instantiate; they are
#                            weak in the original because the linker is expected
#                            to coalesce duplicates)
#   D/R/B data/bss       ->  a strong object
#   A  absolute          ->  SKIPPED. `__bss_start`, `_end` and friends are
#                            synthesised by the linker's script, not emitted by
#                            any compilation unit, so no source file can define
#                            them. rebuild.sh drops them from both sides of the
#                            comparison and says so.
#
# Usage: build-so-stub.sh <arm64-v8a|armeabi-v7a> <output.c>

set -euo pipefail

arch="${1:?arch required}"
out="${2:?output path required}"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
if [ -z "${ARTC_SDK:-}" ]; then
    if [ -d "$REPO/.ref/artemis/WebAssembly" ]; then
        SDK="$REPO/.ref/artemis"
    else
        SDK="$REPO/ports/artemis/vendor/artemis-sdk"
    fi
else
    SDK="$ARTC_SDK"
fi
if [ -f "$SDK/Android/app/src/main/jniLibs/$arch/libartemis.so" ]; then
    LIB="$SDK/Android/app/src/main/jniLibs/$arch/libartemis.so"
else
    LIB="$SDK/Android/$arch/libartemis.so"
fi

NM="/d/emsdk/upstream/bin/llvm-nm.exe"
[ -x "$NM" ] || NM="/c/emsdk/upstream/bin/llvm-nm.exe"
[ -x "$NM" ] || { echo "llvm-nm not found" >&2; exit 1; }
[ -f "$LIB" ] || { echo "no such library: $LIB" >&2; exit 1; }

{
    echo "// Generated by ports/artemis/reverse/build-so-stub.sh -- do not edit."
    echo "//"
    echo "// Defines every dynamic symbol the official libartemis.so exports, so that the"
    echo "// resulting object resolves the same names. See the generator for why this is"
    echo "// the compilable half of the Android reverse engineering rather than the"
    echo "// pseudo-C."
    echo "//"
    echo "// source: $arch/libartemis.so"
    echo

    "$NM" -D --defined-only "$LIB" |
        awk '$2 == "T" { print "void "$3"(void) {}\n" }'
    "$NM" -D --defined-only "$LIB" |
        awk '$2 == "W" { print "__attribute__((weak)) void "$3"(void) {}\n" }'
    "$NM" -D --defined-only "$LIB" |
        awk '$2 == "V" { print "__attribute__((weak)) char "$3"[1];\n" }'
    "$NM" -D --defined-only "$LIB" |
        awk '$2 == "D" || $2 == "R" || $2 == "B" { print "char "$3"[1];\n" }'
} >"$out"

count=$(grep -cE '^(void|__attribute__|char)' "$out" || true)
echo "$out: $count symbol definitions" >&2
