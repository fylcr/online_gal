# Works out exactly which portfile.cmake bytes vcpkg hashed for the gettext ABI, by comparing the
# recorded ABI inputs against the on-disk file, the git HEAD blob, and LF-normalized variants.
# vcpkg records `<filename> <sha256>` lines in buildtrees/<port>/<triplet>.vcpkg_abi_info.txt.
set -u
. "$(dirname "$0")/../../env.sh"
V="$REF_DIR/vcpkg"
cd "$V" || exit 1

echo "== control: a patch file that was NOT edited =="
echo "raw on-disk : $(sha256sum ports/gettext/0001-xgettext-Fix-some-test-failures-on-MSVC.patch | cut -d' ' -f1)"
echo "LF-normalized: $(tr -d '\r' < ports/gettext/0001-xgettext-Fix-some-test-failures-on-MSVC.patch | sha256sum | cut -d' ' -f1)"
echo "ABI recorded : 0fbafedb0e56e978f47ca0009d735947ec539460a63f91659506eaf7c8104155"
echo

echo "== the file under investigation =="
echo "raw on-disk (edited):    $(sha256sum ports/gettext/portfile.cmake | cut -d' ' -f1)"
echo "LF-normalized (edited):  $(tr -d '\r' < ports/gettext/portfile.cmake | sha256sum | cut -d' ' -f1)"
echo "git HEAD blob (pre-edit): $(git cat-file blob HEAD:ports/gettext/portfile.cmake | sha256sum | cut -d' ' -f1)"
echo "ABI recorded:            18435cad4f5987987f15099fc2555236e9c9b5eb3c8de4ce620c087c714ba890"
echo

echo "== does my new patch exist in the ABI inputs at all? =="
grep -c 'fix-mingw-gcc15' buildtrees/gettext/x64-mingw-static.vcpkg_abi_info.txt || true
echo "expected 1 if vcpkg read the port dir on disk, 0 if it read the git tree"
echo

echo "== timestamps: was the ABI info regenerated by the run just now? =="
stat -c '%y  %n' buildtrees/gettext/x64-mingw-static.vcpkg_abi_info.txt
stat -c '%y  %n' buildtrees/gettext/patch-x64-mingw-static-6-err.log
stat -c '%y  %n' ports/gettext/portfile.cmake
stat -c '%y  %n' ports/gettext/fix-mingw-gcc15-localtime-env-loop.patch
echo
date '+%Y-%m-%d %H:%M:%S  (now)'
